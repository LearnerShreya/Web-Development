// ++ increment , -- decrement operator
// sum++ post increment, sum-- post decrement
// ++sum pre increment, --sum pre decrement

// Initialize the variable
let sum = 20;

// Print an initial blank line
console.log("\n");

// Display the value of sum
console.log("Initial value of sum:", sum);

// Post-increment: display sum, then increment
console.log("Post-increment (sum++):", sum++);

// Increment sum again
sum++;
console.log("After another increment (sum++):", sum);

// Pre-increment: increment first, then display
console.log("Pre-increment (++sum):", ++sum);

// Post-decrement: display sum, then decrement
console.log("Post-decrement (sum--):", sum--);

// Decrement sum again
sum--;
console.log("After another decrement (sum--):", sum);

// Pre-decrement: decrement first, then display
console.log("Pre-decrement (--sum):", --sum);

